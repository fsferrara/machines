################################################################################
# MODERN UNIX ALIASES
################################################################################

# Bat: A cat clone with syntax highlighting and Git integration.
alias mcat="bat"

# Eza: Rich directory listings.
alias mls="eza"

# Hunk: Review working-tree diffs.
alias mdiff="hunk diff"

# Dua: Summarize directory disk usage.
alias mdu="dua aggregate"

# Duf: A better version of df in Rust.
alias mdf="duf"

# Eza: Display directory trees.
alias mtree="eza --tree"

# Fd: A simple, fast and user-friendly alternative to find.
alias mfind="fd"

# Ripgrep: A line-oriented search tool that recursively searches the current directory for a regex pattern.
alias mgrep="rg"

# Jq: A lightweight and flexible command-line JSON processor.
alias mjson="jq"

# Sd: A find and replace tool that works with regex.
alias msd="sd"

# Btop: Interactive system and process monitoring.
alias mtop="btop"

# Gping: A ping tool that shows a graph of the ping times.
alias mping="gping"

# Doggo: Command-line DNS client for humans. dig on steroids
alias mdig="doggo"
